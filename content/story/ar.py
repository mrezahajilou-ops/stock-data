SHAHR = ['يناير', 'فبراير', 'مارس', 'أبريل', 'مايو', 'يونيو', 'يوليو', 'أغسطس', 'سبتمبر', 'أكتوبر', 'نوفمبر', 'ديسمبر']


def L(s):
    return '<bdi dir="ltr" class="ltr">%s</bdi>' % s


class F:
    @staticmethod
    def money(v):
        a = abs(v)
        for div, w in ((1e12, 'تريليون دولار'), (1e9, 'مليار دولار'), (1e6, 'مليون دولار')):
            if a >= div:
                n = v / div
                return '%s %s' % (L('%.2f' % n if abs(n) < 10 else ('%.1f' % n if abs(n) < 100 else '%.0f' % n)), w)
        return '%s دولار' % L('{:,.0f}'.format(v))

    @staticmethod
    def count(v):
        return L(v)

    @staticmethod
    def pct(v, d=0):
        return L(('%.' + str(d) + 'f%%') % (v * 100))

    @staticmethod
    def mpct(v):
        return L(('%.1f%%' if abs(v) < 0.1 else '%.0f%%') % (v * 100))

    @staticmethod
    def spct(v):
        if abs(v) < 0.005:
            v = 0.0
        return L('%s%.0f%%' % ('' if v == 0 else '+' if v > 0 else '-', abs(v) * 100))

    @staticmethod
    def num(v):
        return L('%.1f' % v)

    @staticmethod
    def times(v):
        return L('%.1f' % v if v < 10 else '%.0f' % v)

    @staticmethod
    def price(v):
        return L('$' + format(v, ',.2f'))

    @staticmethod
    def years(ys):
        ys = [L(y) for y in ys]
        return ys[0] if len(ys) == 1 else '، '.join(ys[:-1]) + ' و' + ys[-1]


def qdate(s):
    try:
        d = datetime.date.fromisoformat(str(s)[:10])
        return 'الربع المنتهي في %s %s' % (SHAHR[d.month - 1], L(d.year))
    except Exception:
        return 'الربع الأخير'


def month(m):
    return SHAHR[m - 1]


