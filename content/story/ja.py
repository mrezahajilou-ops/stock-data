import datetime


def _d(v, d):
    return ('{:,.%df}' % d).format(v)


class F:
    @staticmethod
    def money(v):
        a = abs(v)
        if a >= 1e12: return '%s兆ドル' % _d(v / 1e12, 2)
        if a >= 1e8: return '%s億ドル' % _d(v / 1e8, 0 if a >= 1e10 else 1)
        if a >= 1e4: return '%s万ドル' % _d(v / 1e4, 0)
        return '%sドル' % _d(v, 0)

    @staticmethod
    def pct(v, d=0):
        return _d(v * 100, d) + '%'

    @staticmethod
    def mpct(v):
        return _d(v * 100, 1 if abs(v) < 0.1 else 0) + '%'

    @staticmethod
    def spct(v):
        if abs(v) < 0.005:
            v = 0.0
        return ('' if v == 0 else '+' if v > 0 else '−') + _d(abs(v) * 100, 0) + '%'

    @staticmethod
    def num(v):
        return _d(v, 1)

    @staticmethod
    def times(v):
        return '%s倍' % _d(v, 1 if v < 10 else 0)

    @staticmethod
    def price(v):
        a = abs(v); d = 2
        if 0 < a < 0.005:
            d = 3 if a >= 0.0005 else 4
        return '%s%sドル' % ('−' if v < 0 and round(a, d) else '', _d(a, d))

    @staticmethod
    def years(ys):
        ys = ['%s年度' % y for y in ys]
        return '、'.join(ys)


def qdate(s):
    try:
        d = datetime.date.fromisoformat(str(s)[:10])
        return '%d年%d月期の四半期' % (d.year, d.month)
    except Exception:
        return '直近の四半期'


def month(m):
    return '%d月' % m


