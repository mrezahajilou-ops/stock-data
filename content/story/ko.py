import re as _re

_PAIRS = {'은(는)': ('은', '는'), '이(가)': ('이', '가'), '을(를)': ('을', '를'), '와(과)': ('과', '와'), '(으)로': ('으로', '로')}
_DIG = {'0': 1, '1': 1, '2': 0, '3': 1, '4': 0, '5': 0, '6': 1, '7': 1, '8': 1, '9': 0}
_PAT = _re.compile(r'((?:<[^>]*>)*)(은\(는\)|이\(가\)|을\(를\)|와\(과\)|\(으\)로)')


def _batchim(ch):
    """True/False when the last sound of ch is known, None when it is not (a Latin name)."""
    o = ord(ch)
    if 0xAC00 <= o <= 0xD7A3:
        return (o - 0xAC00) % 28 != 0
    if ch in _DIG:
        return bool(_DIG[ch])
    if ch == '%':
        return False
    return None


def post(s):
    """Pick the Korean particle after Hangul and numbers; Latin company names keep the 은(는) form."""
    def rep(m):
        start = m.start()
        plain = _re.sub(r'<[^>]*>', '', s[:start] + m.group(1))
        if not plain:
            return m.group(0)
        b = _batchim(plain[-1])
        if b is None:
            return m.group(0)
        a, z = _PAIRS[m.group(2)]
        if m.group(2) == '(으)로' and plain[-1] in '1278' or (m.group(2) == '(으)로' and 0xAC00 <= ord(plain[-1]) <= 0xD7A3 and (ord(plain[-1]) - 0xAC00) % 28 == 8):
            return m.group(1) + z   # ㄹ batchim takes 로
        if m.group(2) == '와(과)':
            return m.group(1) + (a if b else z)
        return m.group(1) + (a if b else z)
    return _PAT.sub(rep, s)
